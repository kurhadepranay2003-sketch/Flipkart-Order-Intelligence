def search_policies(query, top_k=3):

    query_words = set(
        word.lower()
        for word in query.split()
        if len(word) > 2
    )

    scored_documents = []

    for document in policies:

        text = (
            document.get("title", "")
            + " "
            + document.get("content", "")
            + " "
            + " ".join(document.get("keywords", []))
        ).lower()

        score = sum(
            1 for word in query_words
            if word in text
        )

        if score > 0:
            scored_documents.append(
                (score, document)
            )

    scored_documents.sort(
        key=lambda x: x[0],
        reverse=True
    )

    return [
        document
        for _, document in scored_documents[:top_k]
    ]


@tool
def search_policy(query: str) -> str:

    results = search_policies(query)

    if not results:
        return (
            "No relevant policy document was found in the "
            "knowledge base. Do not invent a policy."
        )

    output = []

    for document in results:
        output.append(
            f"Document ID: {document.get('id', 'N/A')}\n"
            f"Title: {document.get('title', 'N/A')}\n"
            f"Content: {document.get('content', '')}"
        )

    return "\n\n".join(output)


@tool
def check_return_risk(
    category: str,
    price_inr: float,
    discount_pct: float,
    customer_tenure_days: int,
    num_previous_orders: int,
    num_previous_returns: int,
    delivery_distance_km: float,
    delivery_days: int,
    is_weekend_order: int,
    rating_given: float = np.nan,
    payment_method: str = "COD"
) -> str:

    input_data = {
        "category": category,
        "price_inr": price_inr,
        "discount_pct": discount_pct,
        "customer_tenure_days": customer_tenure_days,
        "num_previous_orders": num_previous_orders,
        "num_previous_returns": num_previous_returns,
        "delivery_distance_km": delivery_distance_km,
        "delivery_days": delivery_days,
        "is_weekend_order": is_weekend_order,
        "rating_given": rating_given,
        "payment_method": payment_method
    }

    try:

        import pandas as pd

        X = pd.DataFrame([input_data])

        prediction = return_risk_model.predict(X)[0]

        probability = None

        if hasattr(return_risk_model, "predict_proba"):
            probability = return_risk_model.predict_proba(X)[0][1]

        risk = "HIGH" if prediction == 1 else "LOW"

        if probability is not None:
            return (
                f"Return risk: {risk}\n"
                f"Estimated return probability: "
                f"{probability:.2%}"
            )

        return f"Return risk: {risk}"

    except Exception as e:

        return (
            "Unable to calculate return risk using the saved "
            f"model. Error: {str(e)}"
        )


PRODUCT_CLASSES = [
    "T-shirt/top",
    "Trouser",
    "Pullover",
    "Dress",
    "Coat",
    "Sandal",
    "Shirt",
    "Sneaker",
    "Bag",
    "Ankle boot"
]


class ProductClassifier(torch.nn.Module):

    def __init__(self, num_classes=10):

        super().__init__()

        from torchvision.models import resnet18

        self.model = resnet18(
            weights=None
        )

        self.model.fc = torch.nn.Linear(
            self.model.fc.in_features,
            num_classes
        )

    def forward(self, x):
        return self.model(x)


print("Loading Part 2 image classifier...")

if not os.path.exists(IMAGE_MODEL_PATH):
    raise FileNotFoundError(
        f"Image classifier not found: {IMAGE_MODEL_PATH}"
    )

device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

try:

    loaded_model = torch.load(
        IMAGE_MODEL_PATH,
        map_location=device,
        weights_only=False
    )

    if isinstance(
        loaded_model,
        torch.nn.Module
    ):

        image_model = loaded_model

    else:

        image_model = ProductClassifier(
            num_classes=10
        )

        if isinstance(loaded_model, dict):

            if "model_state_dict" in loaded_model:
                state_dict = loaded_model[
                    "model_state_dict"
                ]
            else:
                state_dict = loaded_model

            image_model.load_state_dict(
                state_dict
            )

except Exception as e:

    print(
        "Warning: Could not load image model automatically."
    )

    print(e)

    image_model = None


if image_model is not None:
    image_model.to(device)
    image_model.eval()


