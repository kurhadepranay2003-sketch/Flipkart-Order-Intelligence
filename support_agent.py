@tool
def classify_product_image(image_path: str) -> str:

    if image_model is None:
        return (
            "The product image classifier could not be loaded."
        )

    if not os.path.exists(image_path):
        return (
            f"Image file does not exist: {image_path}"
        )

    try:

        from torchvision import transforms

        transform = transforms.Compose([
            transforms.Grayscale(num_output_channels=3),
            transforms.Resize((224, 224)),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=[0.485, 0.456, 0.406],
                std=[0.229, 0.224, 0.225]
            )
        ])

        image = Image.open(
            image_path
        ).convert("L")

        image_tensor = transform(
            image
        ).unsqueeze(0).to(device)

        with torch.no_grad():

            outputs = image_model(
                image_tensor
            )

            probabilities = torch.softmax(
                outputs,
                dim=1
            )

            confidence, predicted = torch.max(
                probabilities,
                dim=1
            )

        class_index = predicted.item()

        if class_index >= len(PRODUCT_CLASSES):
            return (
                "The model returned an unknown product class."
            )

        product_class = PRODUCT_CLASSES[
            class_index
        ]

        return (
            f"Predicted product category: "
            f"{product_class}\n"
            f"Confidence: {confidence.item():.2%}"
        )

    except Exception as e:

        return (
            "Unable to classify the image.\n"
            f"Error: {str(e)}"
        )


def create_llm():

    api_key = os.getenv(
        "OPENAI_API_KEY"
    )

    if not api_key:
        raise ValueError(
            "OPENAI_API_KEY environment variable is not set."
        )

    return ChatOpenAI(
        model="gpt-4o-mini",
        temperature=0
    )


def create_support_agent():

    llm = create_llm()

    tools = [
        search_policy,
        check_return_risk,
        classify_product_image
    ]

    system_prompt = """
You are a Flipkart customer support assistant.

Your job is to provide accurate and helpful support.

Policy questions must be answered using the search_policy tool.

Never invent or assume a policy that is not present in the knowledge base.

If no relevant policy document is found, clearly say that the available knowledge base does not contain enough information.

Use check_return_risk whenever the user asks about the likelihood or risk of an order being returned.

Use classify_product_image whenever the user provides an image path and asks to identify or classify the product.

Do not hardcode return-risk predictions.

Do not hardcode image classification results.

Explain tool results clearly to the customer.

Keep answers concise, friendly, and professional.

If the user's question requires information that is unavailable, say so instead of making up an answer.
"""

    agent = create_react_agent(
        model=llm,
        tools=tools,
        prompt=system_prompt
    )

    return agent


def ask_agent(agent, question):

    result = agent.invoke(
        {
            "messages": [
                HumanMessage(
                    content=question
                )
            ]
        }
    )

    messages = result["messages"]

    return messages[-1].content


def main():

    print("\n" + "=" * 70)
    print("FLIPKART SUPPORT ASSISTANT")
    print("=" * 70)

    print(
        "\nThe assistant can answer policy questions, "
        "check return risk, and classify product images."
    )

    agent = create_support_agent()

    while True:

        question = input(
            "\nYou: "
        ).strip()

        if question.lower() in [
            "exit",
            "quit",
            "bye"
        ]:

            print(
                "\nSupport Assistant: "
                "Thank you for contacting Flipkart support!"
            )

            break

        if not question:
            continue

        try:

            answer = ask_agent(
                agent,
                question
            )

            print(
                f"\nSupport Assistant: {answer}"
            )

        except Exception as e:

            print(
                "\nSupport Assistant: "
                f"Sorry, something went wrong: {e}"
            )


if __name__ == "__main__":
    main()