def evaluate_classifier(
    model,
    loader
):

    model.eval()

    total_loss = 0.0

    correct = 0

    total = 0


    with torch.no_grad():

        for (
            features,
            labels
        ) in loader:

            features = features.to(
                device
            )

            labels = labels.to(
                device
            )


            outputs = model(
                features
            )


            loss = criterion(
                outputs,
                labels
            )


            total_loss += (

                loss.item()
                *
                labels.size(0)

            )


            predictions = (
                outputs.argmax(
                    dim=1
                )
            )


            correct += (

                predictions == labels

            ).sum().item()


            total += labels.size(0)


    return (

        total_loss / total,

        correct / total

    )


