class ClassifierHead(
    nn.Module
):

    def __init__(
        self,
        input_dim=512,
        num_classes=10
    ):

        super().__init__()

        self.network = nn.Sequential(

            nn.Linear(
                input_dim,
                256
            ),

            nn.ReLU(),

            nn.Dropout(
                0.30
            ),

            nn.Linear(
                256,
                num_classes
            )
        )


    def forward(
        self,
        x
    ):

        return self.network(x)


