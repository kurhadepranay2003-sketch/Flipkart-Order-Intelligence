def extract_features(
    model,
    loader,
    device,
    description
):

    print()
    print(
        description
    )

    feature_list = []

    label_list = []

    model.eval()

    with torch.no_grad():

        for batch_number, (
            images,
            labels
        ) in enumerate(loader):

            images = images.to(
                device,
                non_blocking=True
            )

            features = model(
                images
            )

            feature_list.append(
                features.cpu()
            )

            label_list.append(
                labels.cpu()
            )

            if (
                (batch_number + 1) % 50 == 0
                or
                (batch_number + 1) == len(loader)
            ):

                print(
                    f"  Batch "
                    f"{batch_number + 1}/"
                    f"{len(loader)}"
                )


    features = torch.cat(
        feature_list
    )

    labels = torch.cat(
        label_list
    )


    return features, labels



